import fs from "node:fs";
import path from "node:path";
import { expect, test } from "playwright/test";
import { OUTBOX_DIR } from "./env";
import { activeYear, assignTeacher, db, enroll, loginAs, seedClass, seedFamily, seedSchoolDays, seedTeacher } from "./fixtures";

test("attendance streaks require a staff decision and retain private follow-up history", async ({ page, context }) => {
  const year = await activeYear();
  const schoolClass = await seedClass();
  const family = await seedFamily();
  const teacher = await seedTeacher();
  const studentId = family.students[0].id;
  await enroll(studentId, schoolClass.id, year.id);
  await assignTeacher(teacher.id, schoolClass.id, year.id);
  await seedSchoolDays(year, 3);
  const today = new Intl.DateTimeFormat("sv-SE", { timeZone: "Europe/Oslo" }).format(new Date());
  const { data: schoolDays, error: daysError } = await db().from("school_days").select("id, date").eq("school_year_id", year.id).eq("cancelled", false).lte("date", today).order("date", { ascending: false });
  if (daysError) throw daysError;
  const days = schoolDays.filter((day: { date: string }) => new Date(`${day.date}T12:00:00Z`).getUTCDay() === 0).slice(0, 3);
  expect(days).toHaveLength(3);
  const { error: enrollmentError } = await db().from("enrollments").update({ created_at: `${days[2].date}T00:00:00Z` }).eq("student_id", studentId);
  if (enrollmentError) throw enrollmentError;
  const { error: attendanceError } = await db().from("attendance").insert(days.map((day: { id: string }) => ({ student_id: studentId, school_day_id: day.id, status: "fravaer" })));
  if (attendanceError) throw attendanceError;
  await loginAs(context, teacher.email);
  await page.goto(`/min-side/klasse/${schoolClass.id}?dag=${days[0].id}`);
  const followUp = page.getByRole("region", { name: "Fraværsoppfølging", exact: true });
  await expect(followUp.getByText("3 skolesøndager med sammenhengende fravær", { exact: true })).toBeVisible();
  await followUp.getByLabel("Internt notat", { exact: true }).fill("ZZTEST Private call details");
  await followUp.getByRole("button", { name: "Lagre oppfølging", exact: true }).click();
  await expect(followUp.getByRole("status")).toHaveText("Oppfølging lagret");
  const { data: queuedBefore, error: queueError } = await db().from("school_email_deliveries").select("id").eq("kind", "attendance_followup").eq("family_id", family.id);
  if (queueError) throw queueError;
  expect(queuedBefore).toHaveLength(0);
  await followUp.getByRole("combobox", { name: "Oppfølging", exact: true }).click();
  await page.getByRole("option", { name: "Send e-post til foresatte", exact: true }).click();
  await followUp.getByLabel("Melding til foresatte", { exact: true }).fill("ZZTEST Please contact the school");
  await followUp.getByRole("button", { name: "Send e-post", exact: true }).click();
  await expect(followUp.getByRole("status")).toHaveText("E-post lagt i kø til foresatte");
  await expect.poll(async () => (await db().from("school_email_deliveries").select("status").eq("kind", "attendance_followup").eq("family_id", family.id).single()).data?.status).toBe("sent");
  const messages = fs.readdirSync(OUTBOX_DIR).filter((name) => name.endsWith(".json")).map((name) => JSON.parse(fs.readFileSync(path.join(OUTBOX_DIR, name), "utf8")));
  const email = messages.find((message) => message.to === family.guardians[0].email && message.subject === "Fraværsoppfølging fra Islamskole");
  expect(email.text).toContain("ZZTEST Please contact the school");
  expect(email.text).not.toContain("ZZTEST Private call details");
  await followUp.getByText("Oppfølgingshistorikk", { exact: true }).click();
  await expect(followUp.getByText("ZZTEST Private call details", { exact: true }).first()).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await followUp.scrollIntoViewIfNeeded();
  await page.screenshot({ path: "test-results/attendance-followup-mobile.png" });
  const { error: changeError } = await db().from("attendance").update({ status: "til_stede" }).eq("student_id", studentId).eq("school_day_id", days[1].id);
  if (changeError) throw changeError;
  await page.reload();
  await expect(followUp.getByText("3 skolesøndager med sammenhengende fravær", { exact: true })).toHaveCount(0);
  await followUp.getByText("All oppfølgingshistorikk", { exact: true }).click();
  await expect(followUp.getByText("ZZTEST Private call details", { exact: true })).toBeVisible();
  await loginAs(context, family.guardians[0].email);
  await page.goto(`/min-side/barn/${studentId}`);
  await expect(page.getByText("ZZTEST Private call details", { exact: true })).toHaveCount(0);
});
