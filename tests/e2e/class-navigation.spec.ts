import { expect, test } from "playwright/test";
import { activeYear, assignTeacher, enroll, loginAs, seedAdmin, seedClass, seedFamily, seedSchoolDays, seedTeacher } from "./fixtures";

test("admin opens class information first and reaches the roster separately on mobile", async ({ page, context }) => {
  const year = await activeYear();
  const schoolClass = await seedClass();
  const family = await seedFamily();
  await enroll(family.students[0].id, schoolClass.id, year.id);
  await seedSchoolDays(year, 20);
  const teacher = await seedTeacher();
  await assignTeacher(teacher.id, schoolClass.id, year.id);
  const admin = await seedAdmin();
  await loginAs(context, admin.email);
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto(`/admin/klasser/${schoolClass.id}`);
  await expect(page.getByRole("heading", { name: schoolClass.name, exact: true })).toBeVisible();
  const navigation = page.getByRole("navigation", { name: "Klassevisning", exact: true });
  await expect(navigation.getByRole("link", { name: "Oversikt", exact: true })).toHaveAttribute("aria-current", "page");
  await expect(page.getByRole("heading", { name: "Lærere", exact: true })).toBeVisible();
  await expect(page.getByRole("region", { name: "Klasseinfo", exact: true })).toContainText("Kapasitet");
  await expect(page.getByText(teacher.name, { exact: true })).toBeVisible();
  await expect(page.getByLabel("Kapasitet for klassen", { exact: true })).toHaveCount(0);
  await expect(navigation.getByRole("link")).toHaveCount(3);
  expect((await navigation.boundingBox())!.height).toBeLessThan(65);
  const tabPositions = await navigation.getByRole("link").evaluateAll((links) => links.map((link) => Math.round(link.getBoundingClientRect().top)));
  expect(new Set(tabPositions).size).toBe(1);
  await expect(page.getByRole("link", { name: "Før oppmøte", exact: true })).toHaveAttribute("href", new RegExp(`dagsplan.*klasse=${schoolClass.id}`));
  await page.screenshot({ path: "test-results/class-overview-360.png", animations: "disabled" });
  await page.setViewportSize({ width: 320, height: 800 });
  expect((await navigation.boundingBox())!.height).toBeLessThan(65);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/class-overview-320.png", animations: "disabled" });
  await page.setViewportSize({ width: 360, height: 800 });
  const actions = page.getByRole("button", { name: "Klassehandlinger", exact: true });
  await actions.focus();
  await page.keyboard.press("Enter");
  await page.getByRole("menuitem", { name: "Oppsett for klassen", exact: true }).click();
  await expect(page).toHaveURL(/fane=oppsett/);
  await expect(page.getByRole("heading", { name: "Oppsett for klassen", exact: true })).toBeVisible();
  const capacity = page.getByLabel("Kapasitet for klassen", { exact: true });
  await capacity.fill("101");
  await page.getByRole("button", { name: "Lagre klasseinfo", exact: true }).click();
  await expect(page.getByText("Klasseinfo er lagret", { exact: true })).toBeVisible();
  await navigation.getByRole("link", { name: "Oversikt", exact: true }).click();
  await expect(page.getByRole("region", { name: "Klasseinfo", exact: true })).toContainText("101");
  await navigation.getByRole("link", { name: "Elever", exact: true }).click();
  const student = page.getByRole("link", { name: family.students[0].name }).last();
  await expect(student).toBeVisible();
  await expect(page.getByRole("heading", { name: "Semesterplan", exact: true })).toHaveCount(0);
  await expect(page.getByRole("heading", { name: "Timeplan", exact: true })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await navigation.getByRole("link", { name: "Undervisning", exact: true }).click();
  await page.getByRole("region", { name: "Undervisning", exact: true }).getByRole("link", { name: "Semesterplan", exact: true }).click();
  await expect(page).toHaveURL(/fane=semesterplan/);
  await expect(page.getByRole("heading", { name: "Semesterplan", exact: true })).toBeVisible();
  await expect(student).toHaveCount(0);
  await page.reload();
  await expect(navigation.getByRole("link", { name: "Undervisning", exact: true })).toHaveAttribute("aria-current", "page");
  await navigation.getByRole("link", { name: "Undervisning", exact: true }).click();
  await page.getByRole("region", { name: "Undervisning", exact: true }).getByRole("link", { name: "Materiell", exact: true }).click();
  await expect(page.getByRole("region", { name: "Undervisningsmateriell", exact: true })).toBeVisible();
  await navigation.getByRole("link", { name: "Undervisning", exact: true }).click();
  await page.getByRole("region", { name: "Undervisning", exact: true }).getByRole("link", { name: "Aktiviteter", exact: true }).click();
  await expect(page.getByRole("region", { name: "Klasseaktiviteter", exact: true })).toBeVisible();
  await actions.click();
  await page.getByRole("menuitem", { name: "På nettsiden", exact: true }).click();
  await expect(page.getByRole("button", { name: "Lagre endringer", exact: true })).toBeVisible();
  await navigation.getByRole("link", { name: "Elever", exact: true }).click();
  await expect(student).toBeVisible();
  await page.setViewportSize({ width: 1280, height: 900 });
  await navigation.getByRole("link", { name: "Oversikt", exact: true }).click();
  await expect(navigation.getByRole("link", { name: "Oversikt", exact: true })).toHaveAttribute("aria-current", "page");
  await expect(page.getByRole("region", { name: "Klasseinfo", exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/class-overview-desktop.png", animations: "disabled" });
  await page.goto(`/en/admin/klasser/${schoolClass.id}?fane=semesterplan`);
  await expect(page).toHaveURL(`/admin/klasser/${schoolClass.id}?fane=semesterplan`);
  await expect(navigation.getByRole("link", { name: "Undervisning", exact: true })).toHaveAttribute("aria-current", "page");
  await loginAs(context, family.guardians[0].email);
  await page.goto(`/admin/klasser/${schoolClass.id}?fane=semesterplan`);
  await expect(page.getByRole("navigation", { name: "Klassevisning" })).toHaveCount(0);
});
