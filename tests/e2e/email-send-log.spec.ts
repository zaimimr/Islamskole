import { expect, test } from "playwright/test";
import { activeYear, db, enroll, loginAs, requestLoginLink, seedAdmin, seedClass, seedFamily, waitForLoginLink } from "./fixtures";

test("system login and school emails appear in the admin log without sign-in credentials", async ({ page, context }) => {
  const family = await seedFamily();
  const guardian = family.guardians[0];
  const year = await activeYear();
  const schoolClass = await seedClass();
  await enroll(family.students[0].id, schoolClass.id, year.id);
  const run = await page.request.get("/api/cron/school-emails", { headers: { authorization: "Bearer test" } });
  expect(run.ok()).toBe(true);
  await page.goto("/min-side/logg-inn");
  const since = Date.now();
  await requestLoginLink(page, guardian.email);
  const login = await waitForLoginLink(guardian.email, since);
  await expect.poll(async () => (await db().from("email_send_logs").select("status").contains("recipients", [guardian.email]).eq("subject", "Logg inn på Min side").single()).data?.status).toBe("sent");
  const { data: logs, error } = await db().from("email_send_logs").select("*").contains("recipients", [guardian.email]);
  if (error) throw error;
  expect(logs!.some((log) => log.subject === "Velkommen til Min side på Islamskole Bærum" && log.status === "sent")).toBe(true);
  expect(JSON.stringify(logs)).not.toContain(new URL(login).searchParams.get("token_hash"));
  expect(logs!.every((log) => log.transport === "outbox")).toBe(true);
  const admin = await seedAdmin();
  await loginAs(context, admin.email);
  await page.goto("/admin/beskjeder/epost");
  const log = page.getByRole("region", { name: "Sendelog", exact: true });
  await expect(log.getByText(guardian.email, { exact: true }).first()).toBeVisible();
  await expect(log.getByText("Velkommen til Min side på Islamskole Bærum", { exact: true }).first()).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/email-send-log-mobile.png", animations: "disabled" });
  const sample = { recipients: [guardian.email], subject: "ZZTEST Older logged email", locale: "no", transport: "outbox", status: "sent", completed_at: new Date().toISOString() };
  const { error: pagingError } = await db().from("email_send_logs").insert(Array.from({ length: 51 }, () => ({ ...sample, id: crypto.randomUUID() })));
  if (pagingError) throw pagingError;
  await page.reload();
  await page.getByRole("link", { name: "Eldre", exact: true }).press("Enter");
  await expect(page).toHaveURL(/side=2/);
  await expect(page.getByRole("link", { name: "Nyere", exact: true })).toBeVisible();
  await page.goto("/en/admin/beskjeder/epost");
  await expect(page).toHaveURL("/admin/beskjeder/epost");
  await expect(log).toBeVisible();
  await loginAs(context, guardian.email);
  await page.goto("/admin/beskjeder/epost");
  await expect(page.getByRole("region", { name: "Sendelog", exact: true })).toHaveCount(0);
});
