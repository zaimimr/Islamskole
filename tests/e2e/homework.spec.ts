import { expect, test } from "playwright/test";
import { activeYear, assignTeacher, db, enroll, loginAs, seedClass, seedFamily, seedNote, seedSchoolDays, seedTeacher, zzEmail } from "./fixtures";

test("homework completion and help requests reach teachers and reset when the assignment changes", async ({ page, context }) => {
  const year = await activeYear();
  const schoolClass = await seedClass();
  const family = await seedFamily({ students: [{ childEmail: zzEmail("homework-student") }] });
  const teacher = await seedTeacher();
  await enroll(family.students[0].id, schoolClass.id, year.id);
  await assignTeacher(teacher.id, schoolClass.id, year.id);
  const days = await seedSchoolDays(year, 2);
  const { error: enrollmentError } = await db().from("enrollments").update({ created_at: `${days[0].date}T00:00:00Z` }).eq("student_id", family.students[0].id);
  if (enrollmentError) throw enrollmentError;
  await seedNote(schoolClass.id, days[0].id, "ZZTEST Practise the reading lesson");
  await loginAs(context, family.guardians[0].email);
  const childUrl = `/min-side/barn/${family.students[0].id}`;
  await page.goto(childUrl);
  const homework = page.getByRole("region", { name: "Lekser", exact: true });
  await expect(homework.getByText("ZZTEST Practise the reading lesson", { exact: true })).toBeVisible();
  await homework.getByRole("button", { name: "Fullført", exact: true }).click();
  await expect(homework.getByRole("button", { name: "Fullført", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.reload();
  await expect(homework.getByRole("button", { name: "Fullført", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.screenshot({ path: "test-results/homework-parent-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/homework-parent-mobile.png", fullPage: true });

  await loginAs(context, family.students[0].childEmail!);
  await page.goto("/en/min-side");
  const studentHomework = page.getByRole("region", { name: "Homework", exact: true });
  await studentHomework.getByRole("button", { name: "Need help", exact: true }).click();
  await expect(studentHomework.getByRole("button", { name: "Need help", exact: true })).toHaveAttribute("aria-pressed", "true");
  const { data: response, error } = await db().from("homework_responses").select("note_id, responded_by, homework_version").eq("student_id", family.students[0].id).single();
  if (error) throw error;
  expect(response.responded_by).toBeTruthy();
  expect(response.homework_version).toBe(1);

  await seedNote(schoolClass.id, days[1].id, "ZZTEST Practise vocabulary");
  await loginAs(context, teacher.email);
  await page.goto(`/min-side/klasse/${schoolClass.id}?dag=${days[1].id}`);
  const followUp = page.getByRole("region", { name: "Lekseoppfølging", exact: true });
  const picker = page.getByRole("combobox", { name: "Lekseoppgave", exact: true });
  await picker.click();
  await page.getByRole("option").filter({ hasText: "ZZTEST Practise the reading lesson" }).click();
  await expect(followUp.getByText("Trenger hjelp", { exact: true })).toBeVisible();
  await picker.click();
  await page.getByRole("option").filter({ hasText: "ZZTEST Practise vocabulary" }).click();
  await expect(followUp.getByText("ZZTEST Practise vocabulary", { exact: true })).toBeVisible();
  await expect(followUp.getByText("Ikke fullført", { exact: true })).toBeVisible();
  await picker.click();
  await page.getByRole("option").filter({ hasText: "ZZTEST Practise the reading lesson" }).click();
  await expect(followUp.getByText("Trenger hjelp", { exact: true })).toBeVisible();
  const { error: editError } = await db().from("class_notes").update({ homework: "ZZTEST A changed assignment" }).eq("id", response.note_id);
  if (editError) throw editError;
  await page.reload();
  await expect(followUp.getByText("Ikke fullført", { exact: true })).toBeVisible();
  await expect(followUp.getByText("Trenger hjelp", { exact: true })).toHaveCount(0);

  await loginAs(context, family.guardians[0].email);
  const { error: removeError } = await db().from("class_notes").delete().eq("class_id", schoolClass.id).eq("homework", "ZZTEST Practise vocabulary");
  if (removeError) throw removeError;
  await page.goto(childUrl);
  await expect(homework.getByRole("button", { name: "Fullført", exact: true })).toHaveAttribute("aria-pressed", "false");
  await homework.getByRole("button", { name: "Fullført", exact: true }).click();
  await expect(homework.getByRole("button", { name: "Fullført", exact: true })).toHaveAttribute("aria-pressed", "true");
  await homework.getByRole("button", { name: "Nullstill", exact: true }).click();
  await expect(homework.getByRole("button", { name: "Fullført", exact: true })).toHaveAttribute("aria-pressed", "false");
  const other = await seedFamily();
  await loginAs(context, other.guardians[0].email);
  await page.goto(childUrl);
  await expect(page.getByText("ZZTEST A changed assignment")).toHaveCount(0);
});
