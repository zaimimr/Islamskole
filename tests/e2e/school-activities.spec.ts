import fs from "node:fs";
import path from "node:path";
import { randomUUID } from "node:crypto";
import { expect, test } from "playwright/test";
import { OUTBOX_DIR } from "./env";
import { activeYear, assignTeacher, db, enroll, loginAs, seedClass, seedFamily, seedSchoolDays, seedStudent, seedTeacher, zzEmail } from "./fixtures";

test("activity invitations require per-child guardian consent and produce a private printable participation roster", async ({ page, context }) => {
  const year = await activeYear();
  const schoolClass = await seedClass();
  const family = await seedFamily({ students: [{ childEmail: zzEmail("activity-student") }, {}] });
  const teacher = await seedTeacher();
  for (const student of family.students) await enroll(student.id, schoolClass.id, year.id);
  await assignTeacher(teacher.id, schoolClass.id, year.id);
  await seedSchoolDays(year, 2);
  const today = new Intl.DateTimeFormat("sv-SE", { timeZone: "Europe/Oslo" }).format(new Date());
  const next = new Date(`${today}T12:00:00Z`);
  next.setUTCDate(next.getUTCDate() + (7 - next.getUTCDay() || 7));
  const eventDate = next.toISOString().slice(0, 10);
  const { data: existingDay, error: dayError } = await db().from("school_days").select("id").eq("school_year_id", year.id).eq("date", eventDate).maybeSingle();
  if (dayError) throw dayError;
  if (!existingDay) {
    const { error } = await db().from("school_days").insert({ school_year_id: year.id, date: eventDate });
    if (error) throw error;
  }
  const classUrl = `/min-side/klasse/${schoolClass.id}`;
  await loginAs(context, teacher.email);
  await page.goto(classUrl);
  const activities = page.getByRole("region", { name: "Klasseaktiviteter", exact: true });
  await activities.getByText("Ny aktivitet", { exact: true }).click();
  const editor = page.getByRole("region", { name: "Ny aktivitet", exact: true });
  await editor.getByLabel("Tittel", { exact: true }).fill("ZZTEST Reading activity");
  await editor.getByLabel("Om aktiviteten", { exact: true }).fill("ZZTEST A shared reading Sunday");
  await editor.getByLabel("Samtykketekst", { exact: true }).fill("ZZTEST I consent to the described reading activity");
  await editor.getByLabel("Skolesøndag", { exact: true }).fill(eventDate);
  await editor.getByLabel("Svarfrist", { exact: true }).fill(today);
  await editor.getByRole("button", { name: "Lagre utkast", exact: true }).click();
  await expect(editor.getByRole("status")).toHaveText("Utkast lagret");
  await loginAs(context, family.guardians[0].email);
  await page.goto(`/min-side/barn/${family.students[0].id}`);
  await expect(page.getByText("ZZTEST Reading activity", { exact: true })).toHaveCount(0);
  await loginAs(context, teacher.email);
  await page.goto(classUrl);
  await activities.getByText("ZZTEST Reading activity · Utkast", { exact: true }).click();
  const savedEditor = page.getByRole("region", { name: "Rediger aktivitet ZZTEST Reading activity", exact: true });
  await savedEditor.getByRole("button", { name: "Se gjennom invitasjon", exact: true }).click();
  await expect(savedEditor.getByRole("button", { name: "Publiser invitasjon", exact: true })).toBeVisible();
  const backlog = Array.from({ length: 25 }, () => ({ kind: "signup_parent", entity_id: randomUUID(), family_id: family.id, email: family.guardians[0].email }));
  const { error: backlogError } = await db().from("school_email_deliveries").insert(backlog);
  if (backlogError) throw backlogError;
  await savedEditor.getByRole("button", { name: "Publiser invitasjon", exact: true }).click();
  await expect(activities.getByRole("link", { name: "Samtykke og deltakerliste", exact: true })).toBeVisible();
  const { data: activity, error: activityError } = await db().from("school_activities").select("id").eq("class_id", schoolClass.id).single();
  if (activityError) throw activityError;
  const rosterUrl = `/min-side/aktiviteter/${activity.id}`;
  await page.goto(rosterUrl);
  const roster = page.getByRole("region", { name: "Deltakerliste", exact: true });
  await expect(roster.getByText("Deltar: 0 · Mangler svar: 2", { exact: true })).toBeVisible();
  await expect(roster.getByRole("button", { name: "Deltok", exact: true })).toHaveCount(0);
  await expect.poll(async () => (await db().from("school_email_deliveries").select("status").eq("kind", "activity_consent").eq("entity_id", activity.id).eq("email", family.guardians[0].email).single()).data?.status).toBe("sent");
  const emails = () => fs.readdirSync(OUTBOX_DIR).filter((name) => name.endsWith(".json")).map((name) => JSON.parse(fs.readFileSync(path.join(OUTBOX_DIR, name), "utf8")));
  const invitation = emails().find((email) => email.to === family.guardians[0].email && email.subject === "Samtykke til skoleaktivitet");
  expect(invitation.links[0]).toContain("#activities");
  await loginAs(context, family.guardians[0].email);
  await page.goto(`/min-side/barn/${family.students[0].id}`);
  const childActivities = page.getByRole("region", { name: "Aktiviteter og samtykke", exact: true });
  await expect(childActivities.getByText("ZZTEST I consent to the described reading activity", { exact: true })).toBeVisible();
  await childActivities.getByRole("button", { name: "Samtykker, deltar", exact: true }).click();
  await expect(childActivities.getByRole("status")).toHaveText("Svar lagret");
  await expect(childActivities.getByRole("button", { name: "Samtykker, deltar", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(childActivities.getByRole("button", { name: "Samtykker, deltar", exact: true })).toBeEnabled();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await childActivities.scrollIntoViewIfNeeded();
  await page.screenshot({ path: "test-results/activity-consent-mobile.png", animations: "disabled" });
  await page.goto(`/min-side/barn/${family.students[1].id}`);
  await expect(childActivities.getByText("Venter på svar fra foresatt", { exact: true })).toBeVisible();
  await childActivities.getByRole("button", { name: "Samtykker ikke", exact: true }).click();
  await expect(childActivities.getByRole("status")).toHaveText("Svar lagret");
  await loginAs(context, family.students[0].childEmail!);
  await page.goto("/en/min-side");
  const studentActivities = page.getByRole("region", { name: "Activities and consent", exact: true });
  await expect(studentActivities.getByText("Consented, attending", { exact: true }).first()).toBeVisible();
  await expect(studentActivities.getByRole("button", { name: "I consent, attending", exact: true })).toHaveCount(0);
  const late = await seedStudent(family.id, { firstName: "ZZTEST Late sibling" });
  await enroll(late.id, schoolClass.id, year.id);
  await loginAs(context, teacher.email);
  await page.goto(classUrl);
  await activities.getByRole("button", { name: "Legg til nye elever i klassen", exact: true }).click();
  await expect(activities.getByRole("status")).toHaveText("Aktivitet oppdatert");
  await expect.poll(async () => (await db().from("school_email_deliveries").select("status").eq("kind", "activity_added").eq("family_id", family.id).single()).data?.status).toBe("sent");
  const additional = emails().filter((email) => email.to === family.guardians[0].email && email.subject === "Samtykke til skoleaktivitet");
  expect(additional).toHaveLength(2);
  expect(additional.some((email) => email.text.includes("ZZTEST Late sibling"))).toBe(true);
  await loginAs(context, family.guardians[0].email);
  await page.goto(`/min-side/barn/${late.id}`);
  await expect(childActivities.getByText("Venter på svar fra foresatt", { exact: true })).toBeVisible();
  const past = new Date(next);
  past.setUTCDate(past.getUTCDate() - 14);
  const { error: dateError } = await db().from("school_activities").update({ event_date: past.toISOString().slice(0, 10), respond_by: past.toISOString().slice(0, 10) }).eq("id", activity.id);
  if (dateError) throw dateError;
  await loginAs(context, teacher.email);
  await page.goto(rosterUrl);
  await expect(roster.getByText("Deltar: 1 · Mangler svar: 1", { exact: true })).toBeVisible();
  await expect(roster.getByText("Samtykke avslått", { exact: true })).toBeVisible();
  await roster.getByRole("button", { name: "Deltok", exact: true }).click();
  await expect(roster.getByRole("button", { name: "Deltok", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(roster.getByRole("button", { name: "Deltok", exact: true })).toBeEnabled();
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: "test-results/activity-roster-desktop.png", fullPage: true, animations: "disabled" });
  await page.emulateMedia({ media: "print" });
  await expect(page.locator("[data-portal-shell] > header")).toBeHidden();
  await expect(page.getByRole("button", { name: "Skriv ut deltakerliste", exact: true })).toBeHidden();
  await expect(roster.getByText("Deltok", { exact: true }).first()).toBeVisible();
  await page.emulateMedia({ media: "screen" });
  await page.goto(classUrl);
  await activities.getByRole("button", { name: "Avlys aktivitet", exact: true }).click();
  await activities.getByRole("button", { name: "Avlys og send e-post til foresatte", exact: true }).click();
  await expect(activities.getByText(/Avlyst/, { exact: false })).toBeVisible();
  await expect.poll(async () => (await db().from("school_email_deliveries").select("status").eq("kind", "activity_cancelled").eq("entity_id", activity.id).eq("email", family.guardians[0].email).single()).data?.status).toBe("sent");
  expect(emails().some((email) => email.to === family.guardians[0].email && email.subject === "Skoleaktivitet avlyst")).toBe(true);
  await loginAs(context, family.guardians[0].email);
  await page.goto(`/min-side/barn/${family.students[0].id}`);
  await expect(childActivities.getByText("Avlyst", { exact: true })).toBeVisible();
  await expect(childActivities.getByRole("button", { name: "Samtykker, deltar", exact: true })).toHaveCount(0);
  await page.goto(rosterUrl);
  await expect(page.getByRole("region", { name: "Deltakerliste", exact: true })).toHaveCount(0);
  const other = await seedFamily();
  await loginAs(context, other.guardians[0].email);
  await page.goto(`/min-side/barn/${family.students[0].id}`);
  await expect(page.getByText("ZZTEST Reading activity", { exact: true })).toHaveCount(0);
});
