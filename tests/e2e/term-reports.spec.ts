import fs from "node:fs";
import path from "node:path";
import { OUTBOX_DIR } from "./env";
import { expect, test } from "playwright/test";
import { activeYear, assignTeacher, db, enroll, loginAs, seedClass, seedFamily, seedSchoolDays, seedTeacher, zzEmail } from "./fixtures";

test("teachers review and publish reports while families see retained publications only", async ({ page, context }) => {
  const year = await activeYear();
  const schoolClass = await seedClass();
  const family = await seedFamily({ students: [{ childEmail: zzEmail("report-student") }] });
  const teacher = await seedTeacher();
  const studentId = family.students[0].id;
  await enroll(studentId, schoolClass.id, year.id);
  await assignTeacher(teacher.id, schoolClass.id, year.id);
  const days = await seedSchoolDays(year, 2);
  const { error } = await db().from("enrollments").update({ created_at: `${days[0].date}T00:00:00Z` }).eq("student_id", studentId);
  if (error) throw error;
  await loginAs(context, teacher.email);
  await page.goto(`/min-side/klasse/${schoolClass.id}/elev/${studentId}`);
  const draft = page.getByRole("region", { name: "Rapportutkast", exact: true });
  await draft.getByRole("button", { name: "Åpne utkast", exact: true }).click();
  await expect(draft.getByLabel("Lærerens vurdering", { exact: true })).toBeVisible();
  await draft.getByLabel("Lærerens vurdering", { exact: true }).fill("ZZTEST A reviewed report");
  await draft.getByLabel("Videre øving", { exact: true }).fill("ZZTEST Read together");
  await draft.getByRole("button", { name: "Lagre utkast", exact: true }).click();
  await expect(draft.getByRole("status")).toHaveText("Utkast lagret");
  await loginAs(context, family.guardians[0].email);
  const childUrl = `/min-side/barn/${studentId}`;
  await page.goto(childUrl);
  await expect(page.getByText("ZZTEST A reviewed report", { exact: true })).toHaveCount(0);
  await expect(page.getByRole("region", { name: "Publiserte rapporter", exact: true })).toHaveCount(0);
  await loginAs(context, teacher.email);
  await page.goto(`/min-side/klasse/${schoolClass.id}/elev/${studentId}`);
  await draft.getByRole("button", { name: "Åpne utkast", exact: true }).click();
  await expect(draft.getByLabel("Lærerens vurdering", { exact: true })).toHaveValue("ZZTEST A reviewed report");
  await draft.getByRole("button", { name: "Se gjennom før publisering", exact: true }).click();
  await expect(draft.getByText("ZZTEST A reviewed report", { exact: true })).toBeVisible();
  await expect(draft.getByRole("button", { name: "Publiser rapport", exact: true })).toBeVisible();
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: "test-results/report-review-desktop.png", fullPage: true });
  await draft.getByRole("button", { name: "Publiser rapport", exact: true }).click();
  await expect(draft.getByRole("status")).toHaveText("Rapport publisert");
  const { data: publication, error: publicationError } = await db().from("term_report_publications").select("id").eq("student_id", studentId).single();
  if (publicationError) throw publicationError;
  const { data: delivery, error: deliveryError } = await db().from("school_email_deliveries").select("status, email").eq("kind", "report_published").eq("entity_id", publication.id).single();
  if (deliveryError) throw deliveryError;
  expect(delivery.email).toBe(family.guardians[0].email);
  await expect.poll(async () => (await db().from("school_email_deliveries").select("status").eq("kind", "report_published").eq("entity_id", publication.id).single()).data?.status).toBe("sent");
  const messages = fs.readdirSync(OUTBOX_DIR).filter((name) => name.endsWith(".json")).map((name) => JSON.parse(fs.readFileSync(path.join(OUTBOX_DIR, name), "utf8")));
  const email = messages.find((message) => message.to === family.guardians[0].email && message.subject === "Semesterrapporten til barnet ditt er klar");
  expect(email.links[0]).toContain(`/min-side/rapporter/${publication.id}`);
  expect(email.text).not.toContain("ZZTEST A reviewed report");
  const { error: changeError } = await db().from("term_reports").update({ summary: "ZZTEST Private next draft" }).eq("student_id", studentId);
  if (changeError) throw changeError;
  await loginAs(context, family.guardians[0].email);
  await page.goto(childUrl);
  await page.getByRole("link", { name: /Høstrapport/ }).click();
  await expect(page.getByText("ZZTEST A reviewed report", { exact: true })).toBeVisible();
  await expect(page.getByText("ZZTEST Private next draft", { exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Skriv ut rapport", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: "test-results/report-parent-mobile.png", fullPage: true });
  await page.emulateMedia({ media: "print" });
  await expect(page.locator("[data-portal-shell] > header")).toBeHidden();
  await expect(page.getByRole("button", { name: "Skriv ut rapport", exact: true })).toBeHidden();
  await expect(page.getByText("ZZTEST A reviewed report", { exact: true })).toBeVisible();
  await page.emulateMedia({ media: "screen" });
  await loginAs(context, family.students[0].childEmail!);
  await page.goto(`/en/min-side/rapporter/${publication.id}`);
  await expect(page.getByText("ZZTEST A reviewed report", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Print report", exact: true })).toBeVisible();
  const other = await seedFamily();
  await loginAs(context, other.guardians[0].email);
  await page.goto(`/min-side/rapporter/${publication.id}`);
  await expect(page.getByText("ZZTEST A reviewed report", { exact: true })).toHaveCount(0);
});
